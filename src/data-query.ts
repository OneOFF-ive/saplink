import { z } from 'zod';
import { createCipheriv, createDecipheriv, randomBytes } from 'node:crypto';
import { link, mkdir, readFile, unlink, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { AppError } from './errors.js';

export const entityName = z.string().regex(/^(?:\/[A-Za-z0-9_]+\/)?[A-Za-z_][A-Za-z0-9_]*$/).max(128);

export const fieldName = z.string().regex(/^[A-Za-z_][A-Za-z0-9_]*$/).max(128);

export const queryLimit = z.number().int().min(1).max(500).default(100).describe(("Maximum returned rows, default 100, maximum 500. Does not bound database scan cost; prefer a small value " +
  "and selective filters."));
const cursorSchema = z.string().min(1).max(16384).regex(/^[a-zA-Z0-9_-]+$/);

export const tableQuerySchema = z.object({
  table_name: entityName.describe('DDIC table or backend-supported entity name, e.g. MARA. Not a SQL expression or URL.'),
  fields: z.array(fieldName).min(1).max(100).optional().describe('Columns to return, e.g. ["MATNR", "MTART"]. Omit for all columns; prefer only fields needed for the task.'),
  filters: z.array(z.object({
    field: fieldName,
    operator: z.enum(['eq', 'ne', 'gt', 'ge', 'lt', 'le', 'like']),
    value: z.string().max(2048).describe('Raw value as a string; do not add SQL quotes. Preserve leading zeros. LIKE uses % and _ wildcards.')
  }).strict()).max(50).default([]).describe('AND-combined comparisons. Example: [{"field":"MTART","operator":"eq","value":"FERT"}]. No OR or SQL fragments.'),
  limit: queryLimit,
  pagination: z.boolean().optional().describe('Enable primary-key pagination for a supported DDIC table.'),
  cursor: cursorSchema.optional().describe(
    'Use next_cursor from a previous page with the same connection, table, fields and filters. Implies pagination.')
}).strict();

export const sqlQuerySchema = z.object({
  sql: z.string().trim().min(1).max(16384).describe(("One read-only ABAP SQL SELECT with FROM, e.g. SELECT matnr FROM mara WHERE mtart = 'FERT'. No terminator, " +
    "comments, INTO or CLIENT/CLIENTS overrides. Use ~ for qualified fields; never insert untrusted values as " +
    "SQL syntax.")),
  limit: queryLimit,
  pagination: z.boolean().optional().describe(
    'Page a SELECT or inner join. End the SQL with ORDER BY explicit, projected character or NUMC columns that together uniquely identify a row.'),
  cursor: cursorSchema.optional().describe(
    'Use next_cursor with the same connection and SQL text. Implies pagination.')
}).strict();

export type TableQuery = z.input<typeof tableQuerySchema>;

export type SqlQuery = z.input<typeof sqlQuerySchema>;

const sqlOperators = {
  eq: '=',
  ne: '<>',
  gt: '>',
  ge: '>=',
  lt: '<',
  le: '<=',
  like: 'LIKE'
};

function sqlLiteral(value: string) { return `'${value.replace(/'/g, "''")}'`; }

export function tableQuery(input: TableQuery) {
  const query = tableQuerySchema.parse(input);
  const tableName = query.table_name.toUpperCase();
  const conditions = query.filters.map(filter => {
    const field = filter.field.toUpperCase();
    const operator = sqlOperators[filter.operator];
    return `${field} ${operator} ${sqlLiteral(filter.value)}`;
  });
  const fields = query.fields?.map(field => field.toUpperCase());
  const whereClause = conditions.length ? ` WHERE ${conditions.join(' AND ')}` : '';
  // An empty body uses the basic DDIC preview, including on older systems.
  const needsCustomQuery = query.fields !== undefined || query.filters.length > 0;
  const sql = needsCustomQuery ? `SELECT ${fields?.join(', ') ?? '*'} FROM ${tableName}${whereClause}` : '';
  return {
    ...query,
    table_name: tableName,
    fields,
    conditions,
    sql
  };
}

const cursorValues = z.array(z.string().max(512).refine(value => !/[\x00-\x1f\x7f]/.test(value))).min(1).max(32);

export async function loadQueryCursorKey(directory: string) {
  const path = join(directory, 'table-cursor.key');
  const read = async () => {
    const key = await readFile(path);
    if (key.length !== 32) throw new AppError('INVALID_CONFIG', 'Invalid local query pagination key');
    return key;
  };
  try { return await read(); }
  catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error; }
  await mkdir(directory, { recursive: true });
  const temporary = `${path}.${randomBytes(12).toString('hex')}`;
  await writeFile(temporary, randomBytes(32), { mode: 0o600, flag: 'wx' });
  try {
    // Publish a complete key without replacing one generated by another CLI process.
    try { await link(temporary, path); }
    catch (error) { if ((error as NodeJS.ErrnoException).code !== 'EEXIST') throw error; }
    return await read();
  } finally { await unlink(temporary); }
}

function decodeQueryCursor(cursor: string, scope: Buffer, secret: Buffer): unknown {
  const encoded = Buffer.from(cursor, 'base64url');
  if (encoded.length <= 28 || encoded.toString('base64url') !== cursor) throw new Error('Invalid cursor encoding');
  const decipher = createDecipheriv('aes-256-gcm', secret, encoded.subarray(0, 12));
  decipher.setAAD(scope);
  decipher.setAuthTag(encoded.subarray(12, 28));
  return JSON.parse(Buffer.concat([decipher.update(encoded.subarray(28)), decipher.final()]).toString('utf8'));
}

function encodeQueryCursor(boundary: unknown, scope: Buffer, secret: Buffer) {
  const iv = randomBytes(12);
  const cipher = createCipheriv('aes-256-gcm', secret, iv);
  cipher.setAAD(scope);
  const encrypted = Buffer.concat([cipher.update(JSON.stringify(boundary), 'utf8'), cipher.final()]);
  const cursor = Buffer.concat([iv, cipher.getAuthTag(), encrypted]).toString('base64url');
  if (cursor.length > 16384)
    throw new AppError('QUERY_PAGINATION_UNSUPPORTED', 'SAP ordering values exceed the cursor size limit');
  return cursor;
}

function keyBranches(keys: { column: string; descending?: boolean }[], boundary: string[]) {
  const equal = keys.map(({ column }, i) => `${column} = ${sqlLiteral(boundary[i])}`);
  // Disjoint branches in result order avoid grouped OR in SAP Data Preview.
  return keys.map(({ column, descending }, i) =>
    [...equal.slice(0, i), `${column} ${descending ? '<' : '>'} ${sqlLiteral(boundary[i])}`]).reverse();
}

export function pagedTableQuery(query: ReturnType<typeof tableQuery>, keys: string[], target: string, secret: Buffer) {
  const scope = Buffer.from(JSON.stringify(['table-page-v1', target, query.table_name, query.sql, keys]));
  let branches: string[][] = [[]];
  let after: string[] | undefined;
  if (query.cursor) {
    try {
      after = cursorValues.parse(decodeQueryCursor(query.cursor, scope, secret));
      if (after.length !== keys.length) throw new Error('Cursor does not match primary key');
    } catch {
      throw new AppError('INVALID_QUERY_CURSOR', 'Use the original connection, table, fields and filters with next_cursor');
    }
    branches = keyBranches(keys.map(column => ({ column })), after);
  }
  const selected = query.fields ? [...new Set([...query.fields, ...keys])].join(', ') : '*';
  const statements = branches.map(branch => {
    const conditions = [...query.conditions, ...branch];
    const where = conditions.length ? ` WHERE ${conditions.join(' AND ')}` : '';
    return `SELECT ${selected} FROM ${query.table_name}${where} ORDER BY ${keys.join(', ')}`;
  });
  return { statements, scope, after };
}

export function pagedTableResult(result: ReturnType<typeof queryResult>, fields: string[] | undefined,
  keys: string[], page: ReturnType<typeof pagedTableQuery>, secret: Buffer) {
  const seen = new Set(page.after ? [JSON.stringify(page.after)] : []);
  let lastKey: string[] | undefined;
  for (const row of result.rows as Record<string, unknown>[]) {
    const key = cursorValues.safeParse(keys.map(field => row[field]));
    if (!key.success || seen.has(JSON.stringify(key.data)))
      throw new AppError('QUERY_PAGINATION_UNSUPPORTED', 'SAP did not return distinct, usable primary-key values');
    seen.add(JSON.stringify(key.data));
    lastKey = key.data;
  }
  const next = result.truncated && lastKey ? encodeQueryCursor(lastKey, page.scope, secret) : null;
  const columns = result.columns as { name: string }[];
  const rows = result.rows as Record<string, unknown>[];
  return { ...result, pagination_supported: true, next_cursor: next,
    columns: fields ? columns.filter(column => fields.includes(column.name)) : columns,
    rows: fields ? rows.map(row => Object.fromEntries(Object.entries(row).filter(([field]) => fields.includes(field)))) : rows };
}

// Mask literals while preserving positions and line breaks outside them. Tokens inside
// user data must not be mistaken for SQL commands or client-handling clauses.
function maskSqlLiterals(sql: string) {
  let maskedSql = '';
  let insideLiteral = false;
  for (let index = 0; index < sql.length; index++) {
    const character = sql[index];
    if (character === "'") {
      if (insideLiteral && sql[index + 1] === "'") {
        maskedSql += '  ';
        index++;
        continue;
      }
      insideLiteral = !insideLiteral;
      maskedSql += ' ';
      continue;
    }
    maskedSql += insideLiteral ? ' ' : character;
  }
  return {
    maskedSql,
    hasUnclosedLiteral: insideLiteral
  };
}

const forbiddenSqlKeywords = new Set([
  'INSERT', 'UPDATE', 'DELETE', 'MODIFY', 'MERGE', 'UPSERT', 'DROP', 'ALTER', 'CREATE',
  'TRUNCATE', 'EXEC', 'EXECUTE', 'CALL', 'COMMIT', 'ROLLBACK', 'INTO', 'APPENDING',
  'EXPORT', 'IMPORT', 'OPEN', 'FETCH', 'CLOSE', 'GRANT', 'REVOKE',
  'CLIENT', 'CLIENTS', 'CONNECTION', 'PRIVILEGED'
]);

export function readOnlySql(input: SqlQuery) {
  const query = sqlQuerySchema.parse(input);
  const { maskedSql, hasUnclosedLiteral } = maskSqlLiterals(query.sql);
  const keywords: string[] = maskedSql.toUpperCase().match(/[A-Z_][A-Z0-9_]*/g) ?? [];
  const isSelectWithFrom = /^\s*SELECT\b/i.test(maskedSql) && keywords.includes('FROM');
  const hasForbiddenKeyword = keywords.some(keyword => forbiddenSqlKeywords.has(keyword));
  const hasCommentOrDelimiter = /[;"`{}\x00-\x08\x0b\x0c\x0e-\x1f]|--|\/\*|\*\//.test(maskedSql)
    || /^\s*\*/m.test(maskedSql);
  // A decimal point is permitted; a statement-ending ABAP period is not.
  const hasStatementPeriod = /\.(?!\d)/.test(maskedSql);
  if (hasUnclosedLiteral || !isSelectWithFrom || hasForbiddenKeyword || hasCommentOrDelimiter || hasStatementPeriod) {
    throw new AppError('INVALID_QUERY', ("Use a single SELECT with FROM. Comments, statement terminators, write statements, INTO, client overrides " +
      "and privileged access are not supported."));
  }
  return query;
}

function topLevelSql(sql: string) {
  const { maskedSql } = maskSqlLiterals(sql);
  let depth = 0;
  const top = maskedSql.replace(/[\s\S]/g, character => {
    if (character === '(') { depth++; return ' '; }
    if (character === ')') {
      if (!depth) throw new AppError('INVALID_QUERY', 'Unbalanced SQL parentheses');
      depth--;
      return ' ';
    }
    return depth ? ' ' : character;
  });
  if (depth) throw new AppError('INVALID_QUERY', 'Unbalanced SQL parentheses');
  return top;
}

const previewSqlLineLimit = 240;

function formatPreviewSql(sql: string) {
  // Older Data Preview backends can truncate long source lines. Split only
  // on whitespace outside string literals and leave the original SQL in the cursor scope.
  if (sql.split(/\r?\n/).every(line => Buffer.byteLength(line) <= previewSqlLineLimit)) return sql;
  const lines: string[] = [];
  let start = 0;
  let line = '';
  const append = (part: string) => {
    if (!part) return;
    const bytes = Buffer.byteLength(part);
    if (bytes > previewSqlLineLimit)
      throw new AppError('QUERY_PAGINATION_UNSUPPORTED', 'A SQL token or literal is too long for paginated SAP Data Preview');
    if (line && Buffer.byteLength(line) + 1 + bytes > previewSqlLineLimit) {
      lines.push(line);
      line = '';
    }
    line = line ? `${line} ${part}` : part;
  };
  for (const match of sql.matchAll(/'(?:''|[^'])*'|(\s+)/g)) {
    if (!match[1]) continue;
    append(sql.slice(start, match.index));
    start = match.index + match[0].length;
  }
  append(sql.slice(start));
  lines.push(line);
  return lines.join('\n');
}

const sqlColumn = '(?:[A-Z_][A-Z0-9_]*~)?[A-Z_][A-Z0-9_]*';
const orderTerm = new RegExp(`^(${sqlColumn})(?:\\s+(ASCENDING|DESCENDING))?$`, 'i');
const projectedColumn = new RegExp(`^(${sqlColumn})(?:\\s+AS\\s+([A-Z_][A-Z0-9_]*))?$`, 'i');

export function pagedSqlQuery(query: ReturnType<typeof readOnlySql>, target: string, secret: Buffer) {
  const invalid = () => new AppError('QUERY_PAGINATION_UNSUPPORTED',
    'Use a SELECT or inner join with explicit unique ORDER BY columns in the result. Grouping, outer joins, row limits and top-level OR filters are unsupported in pagination mode.');
  const top = topLevelSql(query.sql);
  const from = /\bFROM\b/i.exec(top);
  const order = /\bORDER\s+BY\b/i.exec(top);
  const where = /\bWHERE\b/i.exec(top);
  if (!from || !order || from.index >= order.index ||
      /\b(?:SINGLE|OFFSET|UP\s+TO|GROUP\s+BY|HAVING|UNION|INTERSECT|EXCEPT|FOR\s+ALL\s+ENTRIES|BYPASSING\s+BUFFER|(?:LEFT|RIGHT|FULL)(?:\s+OUTER)?\s+JOIN)\b/i.test(top) ||
      (where && /\bOR\b/i.test(top.slice(where.index + where[0].length, order.index)))) throw invalid();

  const projection = top.slice('SELECT'.length, from.index).replace(/^\s*DISTINCT\s+/i, ' ');
  const columns = projection.split(',').flatMap(value => {
    const match = projectedColumn.exec(value.trim());
    if (!match) return [];
    const column = match[1].toUpperCase();
    return [{ column, name: (match[2] ?? column.split('~').at(-1)!).toUpperCase() }];
  });
  const keys = query.sql.slice(order.index + order[0].length).split(',').map(value => {
    const match = orderTerm.exec(value.trim());
    if (!match) throw invalid();
    const ref = match[1].toUpperCase();
    const matching = columns.filter(field => field.column === ref || field.name === ref);
    if (matching.length !== 1) throw invalid();
    return { ...matching[0], descending: match[2]?.toUpperCase() === 'DESCENDING' };
  });
  if (keys.length > 32 || new Set(keys.map(key => key.name)).size !== keys.length) throw invalid();

  const scope = Buffer.from(JSON.stringify(['sql-page-v1', target, query.sql]));
  if (!query.cursor) return { statements: [formatPreviewSql(query.sql)], keys, scope, after: undefined };
  let after: string[];
  try {
    after = cursorValues.parse(decodeQueryCursor(query.cursor, scope, secret));
    if (after.length !== keys.length) throw new Error('Cursor does not match ordering columns');
  } catch {
    throw new AppError('INVALID_QUERY_CURSOR', 'Use the original connection and SQL text with next_cursor');
  }
  const beforeOrder = query.sql.slice(0, order.index).trimEnd();
  const orderBy = query.sql.slice(order.index);
  const statements = keyBranches(keys, after).map(branch =>
    formatPreviewSql(`${beforeOrder}${where ? ' AND ' : ' WHERE '}${branch.join(' AND ')} ${orderBy}`));
  return { statements, keys, scope, after };
}

export function pagedSqlResult(result: ReturnType<typeof queryResult>, limit: number,
  page: ReturnType<typeof pagedSqlQuery>, secret: Buffer) {
  const names = page.keys.map(key => key.name);
  const columns = result.columns as { name: string; type: string }[];
  for (const name of names) {
    const matching = columns.filter(column => column.name.toUpperCase() === name);
    if (matching.length !== 1 || !['C', 'N'].includes(matching[0].type))
      throw new AppError('QUERY_PAGINATION_UNSUPPORTED', 'SQL ordering keys must be distinct projected character or NUMC columns');
  }
  const returnedNames = names.map(name => columns.find(column => column.name.toUpperCase() === name)!.name);
  const seen = new Set(page.after ? [JSON.stringify(page.after)] : []);
  let lastKey: string[] | undefined;
  for (const [index, row] of (result.rows as Record<string, unknown>[]).entries()) {
    const key = cursorValues.safeParse(returnedNames.map(name => row[name]));
    if (!key.success || key.data.some(value => Buffer.byteLength(sqlLiteral(value)) > previewSqlLineLimit) ||
        seen.has(JSON.stringify(key.data)))
      throw new AppError('QUERY_PAGINATION_UNSUPPORTED', 'ORDER BY columns must uniquely identify each row and have usable values');
    seen.add(JSON.stringify(key.data));
    if (index < limit) lastKey = key.data;
  }
  const truncated = result.rows.length > limit;
  const next = truncated && lastKey ? encodeQueryCursor(lastKey, page.scope, secret) : null;
  return { ...result, rows: result.rows.slice(0, limit), row_count: Math.min(result.rows.length, limit),
    limit, truncated, pagination_supported: true, next_cursor: next };
}

export function queryResult(result: {
  columns: unknown[];
  values: unknown[];
}, limit: number) {
  if (!result.columns.length)
    throw new AppError('QUERY_RESPONSE_INVALID', 'SAP did not return tabular query metadata');
  return {
    columns: result.columns,
    rows: result.values.slice(0, limit),
    row_count: Math.min(result.values.length, limit),
    limit,
    truncated: result.values.length > limit,
    pagination_supported: false
  };
}

type DiscoveryWorkspace = {
  collection: {
    href: string;
    templateLinks: {
      template: string;
    }[];
  }[];
};

function discoveryLinkMatchesPath(link: string, path: string): boolean {
  try {
    const withoutTemplateParameters = link.replace(/\{[^}]*\}/g, '');
    const url = new URL(withoutTemplateParameters, 'http://adt.local/sap/bc/adt/');
    return url.pathname === path;
  }
  catch {
    return false;
  }
}

export function queryCapabilities(discovery: DiscoveryWorkspace[]) {
  const links = discovery.flatMap(workspace => workspace.collection.flatMap(collection => [
    collection.href,
    ...collection.templateLinks.map(link => link.template)
  ]));
  const isAdvertised = (path: string) => links.some(link => discoveryLinkMatchesPath(link, path));
  return {
    table_query: { advertised: isAdvertised('/sap/bc/adt/datapreview/ddic') },
    sql_query: { advertised: isAdvertised('/sap/bc/adt/datapreview/freestyle') },
    availability_policy: 'Discovery advertisement is not authorization. Unadvertised endpoints may still work; actual queries establish availability.',
    max_rows: 500,
    values: 'raw_strings',
    client_policy: 'configured_client_only'
  };
}
